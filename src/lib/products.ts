export function getAllProducts(): Product[] {
  return products;
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByBrand(brandSlug: string): Product[] {
  return products.filter((p) => p.brandSlug === brandSlug);
}

export function getProductsByColor(colorSlug: string): Product[] {
  return products.filter((p) =>
    p.colorVariants.some((c) => c.slug === colorSlug)
  );
}

export function getFeaturedProducts(): Product[] {
  return products.filter((p) => p.isFeatured);
}

export function getNewProducts(): Product[] {
  return products.filter((p) => p.isNew);
}

export function getRelatedProducts(
  currentSlug: string,
  limit: number = 3
): Product[] {
  const current = getProductBySlug(currentSlug);
  if (!current) return products.slice(0, limit);

  // Prefer same brand, then same category
  const sameBrand = products
    .filter((p) => p.brandSlug === current.brandSlug && p.slug !== currentSlug);
  const others = products
    .filter((p) => p.brandSlug !== current.brandSlug && p.slug !== currentSlug);

  return [...sameBrand, ...others].slice(0, limit);
}

export function getProductSlugs(): string[] {
  return products.map((p) => p.slug);
}

export function getAllColors(): { name: string; hex: string; slug: string }[] {
  const colorsMap = new Map<string, { name: string; hex: string; slug: string }>();
  products.forEach((p) =>
    p.colorVariants.forEach((c) => {
      if (!colorsMap.has(c.slug)) colorsMap.set(c.slug, c);
    })
  );
  return Array.from(colorsMap.values());
}

export function searchProducts(query: string): Product[] {
  const lower = query.toLowerCase();
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(lower) ||
      p.brand.toLowerCase().includes(lower) ||
      p.compatibleModels.some((m) => m.toLowerCase().includes(lower)) ||
      p.featureTags.some((t) => t.toLowerCase().includes(lower))
  );
}
